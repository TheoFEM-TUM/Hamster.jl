"""
    clear_hamster_output(; output_files=["hamster_out.h5", "hamster.out", "Es.dat", "vs.dat"])

Delete output files generated by Hamster.

# Keyword Arguments
- `output_files::Vector{String}`: List of filenames to remove. Defaults to
  `["hamster_out.h5", "hamster.out", "Es.dat", "vs.dat"]`.
"""
function clear_hamster_output(; output_files=["hamster_out.h5", "hamster.out", "ham.h5", "Es.dat", "vs.dat"])
    for file in output_files
        if isfile(file); rm(file, force=true); end
    end
end

"""
    generate_output(conf::Config)

Generates the main output file `hamster.out` with initial run information.

# Arguments
- `conf::Config`: A configuration object containing parameters and settings for the current run.

# Details
This function performs the following tasks:
1. Opens (creates) the file `hamster.out` for writing.
2. Writes the current date and time to the file to record when the Hamster run started.
3. Writes the list of unique hostnames.
"""
function generate_output(conf::Config=get_empty_config(); hostnames=hostnames)
    open("hamster.out", "w") do hamster_out
        print_hamster(hamster_out)

        # Write current date and time of day
        dt = now(); date = Date(dt); time = Time(dt)
        println(hamster_out, "Starting Hamster run on $date at $time.")
        hostlist = string.(unique(hostnames))
        hostlist = replace("$hostlist", "["=>"", "]"=>"")
        println(hamster_out, "  Hamster is running on host(s): $hostlist")
        println(hamster_out, "  Linear algebra (BLAS/LAPACK): $(linear_algebra_library())")
        write_separator(hamster_out)
    end
end

"""
    linear_algebra_library()

Name of the BLAS/LAPACK library that Julia uses (OpenBLAS by default, Intel MKL if MKL.jl is loaded, e.g., after
`hamster --install --mkl`) and its file name.
"""
function linear_algebra_library()
    libname = basename(blas_library())
    name = uses_mkl() ? "Intel MKL" : occursin("openblas", libname) ? "OpenBLAS" : "other"
    return "$name ($libname)"
end

"""
    write_separator(hamster_out)

Write a separator line of `L` times `char`` to the `io_stream`.

# Arguments
- `io_stream::IO`: The io stream to which the separator will be written.
"""
write_separator(io_stream; char='=', L=80) = println(io_stream, char^L)

"""
    append_output_block(block_title, block_tags, block_values; filename="hamster.out")

Append a formatted block of output to the specified file, typically used for logging or report generation.

# Arguments
- `block_title::AbstractString`: The title of the block to be appended. This title will be written as a header.
- `block_tags::AbstractVector{<:AbstractString}`: A vector of tags or labels corresponding to the block's values.
- `block_values::AbstractVector{<:Any}`: A vector of values corresponding to the tags, representing the content to be written.
- `filename::AbstractString`: The name of the file to which the block will be appended. Defaults to `"hamster.out"`.

# Usage
- This function checks if the specified file exists. If it does, it appends a titled block of information with tags and corresponding values.
- Each tag-value pair is written on a new line using the `write_output_line` function.
- A separator line is written after the block for clarity.
"""
function append_output_block(block_title, block_tags, block_values; filename="hamster.out")
    if filename in readdir()
        hamster_out = open("hamster.out", "a")
        println(hamster_out, block_title)
        for (tag, value) in zip(block_tags, block_values)
            write_output_line(hamster_out, tag, value)
        end
        write_separator(hamster_out)
        println(hamster_out, "")
        close(hamster_out)
    end
end

function write_block_summary(block_label, filename="hamster.out"; kwargs...)
    if filename in readdir()
        open(filename, "a") do io
            write(io, "  $block_label Summary\n")
            write_separator(io, char='-')
            for (key, value) in kwargs
                key_string = rpad(replace("      $key:", "["=>"", "]"=>""), 34)
                value_string = rpad(replace("      $value", "["=>"", "]"=>""), 40)
                write(io, "$key_string $value_string\n")
            end
            write_separator(io)
        end
    end
end

"""
    write_output_line(dyntb_out, key, value, L)

Write a line with `key` and `value` pair to the output file `dyntb_out`.
"""
function write_output_line(hamster_out, key, value; L=25)
    key_string = L-length(key) < 0 ? string(key[1:L]) : string(key)
    value_string = L+15-length(value) < 0 ? string(value[1:L]) : string(value)
    Lk = length(key_string); Lv = length(value_string)
    println(hamster_out, "   ", key_string*" "^(L-Lk), " = ", " "^(L+15-Lv)*value_string)
end

"""
    append_output_line(line; filename="hamster.out")

Append a `line` to the output file `hamster.out`.
"""
function append_output_line(line; filename="hamster.out")
    open(filename, "a") do f
        println(f, line)
    end
end

"""
    write_config_tags(filename::String, conf::Config; blocks=nothing, show_desc=false)

Pretty print configuration tags to an output file in a nicely formatted style.

# Arguments
- `filename`: Path to the output file.
- `conf`: Configuration object to read current values.
- `blocks`: Optional list of block names to print. If `nothing`, all blocks are printed.
- `show_desc`: If `true`, adds the description as a comment on each line.

The pair cutoffs `rcut_<A>_<B>` that are set follow the tags of the Options block.
"""
function write_config_tags(conf::Config; blocks=nothing, show_desc=false, filename="hamster.out")
    open(filename, "a") do io
        println(io)
        println(io, "The following input parameters are used:")
        println(io)

        # Organize tags by block
        tags_by_block = Dict{String, Vector{ConfigTag}}()
        for tag in config_tags()
            tag.per_atom && continue                  # set per species in the atom blocks
            push!(get!(tags_by_block, tag.block, Vector{ConfigTag}()), tag)
        end

        blocks_to_print = blocks === nothing ? sort(collect(keys(tags_by_block)), by=block_order) : filter(b -> haskey(tags_by_block, b), blocks)

        # Determine column for # comments (fixed for all tags)
        tagval_col_width = maximum(length("    $(tag.name) = $(tag_value(conf, tag))") for tags in values(tags_by_block) for tag in tags)
        desc_col_start = tagval_col_width + 4  # 4 spaces before #

        for blk in blocks_to_print
            write_separator(io)
            println(io, "  $blk")
            write_separator(io, char='-')

            for tag in tags_by_block[blk]
                tag_val = tag_value(conf, tag)
                val = isa(tag_val, AbstractString) ? tag_val : isnothing(tag_val) ? "none" : join(tag_val, " ")
                tagval_str = "    $(tag.name) = $(val)"
                tagval_padded = rpad(tagval_str, desc_col_start)

                if show_desc && !isempty(tag.description)
                    wrap_width = max(80 - desc_col_start - 2, 20)
                    desc_lines = wrap_text(tag.description, wrap_width)
                    # First line appended to tag=value
                    println(io, tagval_padded, "# ", desc_lines[1])
                    # Remaining lines aligned under the first #
                    for l in desc_lines[2:end]
                        println(io, rpad(" ", desc_col_start), "  ", l)
                    end
                else
                    println(io, tagval_str)
                end
            end
            if blk == "Options"                       # pair cutoffs rcut_<A>_<B> (not in the tag registry)
                for ((a, b), value) in sort(collect(get_pair_rcuts(conf)))
                    tagval_str = "    rcut_$(a)_$(b) = $(value)"
                    println(io, show_desc ? rpad(tagval_str, desc_col_start) * "# cutoff of the pair $a-$b" : tagval_str)
                end
            end

            write_separator(io)
            println(io)
        end
    end
end

# Helper to wrap text into multiple lines
function wrap_text(text::AbstractString, width::Int)
    words = split(text)
    lines = String[]
    line = ""
    for w in words
        if !isempty(line) && textwidth(line) + 1 + textwidth(w) > width
            push!(lines, line)
            line = w
        else
            line = isempty(line) ? w : line * " " * w
        end
    end
    if !isempty(line)
        push!(lines, line)
    end
    return lines
end
"""
    OutputLogger(logger; filename="hamster.out")

Logger of a run on the first MPI rank. It passes all messages on to `logger` (the console) and also writes warnings and
errors to `filename`, so that they are not only in the standard error of the job. Messages that come before the header
of `filename` is written (e.g., the checks of the config file) are kept and written by
[`start_output_log!`](@ref Hamster.start_output_log!). A message that was already written is not written again (e.g.,
the same warning in every trial of a hyperparameter optimization). Messages of the group `:hamster_out` are written to
`filename` by the code that logs them (e.g., inside a model summary) and are only passed on.
"""
mutable struct OutputLogger <: Logging.AbstractLogger
    logger::Logging.AbstractLogger
    filename::String
    pending::Vector{String}
    written::Set{String}
    started::Bool
    nwarnings::Int64
    lock::ReentrantLock
end

OutputLogger(logger; filename="hamster.out") = OutputLogger(logger, filename, String[], Set{String}(), false, 0, ReentrantLock())

Logging.min_enabled_level(logger::OutputLogger) = min(Logging.min_enabled_level(logger.logger), Logging.Warn)

Logging.shouldlog(logger::OutputLogger, level, _module, group, id) =
    level ≥ Logging.Warn || Logging.shouldlog(logger.logger, level, _module, group, id)

Logging.catch_exceptions(logger::OutputLogger) = Logging.catch_exceptions(logger.logger)

function Logging.handle_message(logger::OutputLogger, level, message, _module, group, id, file, line; kwargs...)
    if level ≥ Logging.Warn && group ≠ :hamster_out
        log_to_output!(logger, output_log_line(level, message; kwargs...), count=level < Logging.Error)
    elseif level ≥ Logging.Warn
        lock(() -> logger.nwarnings += 1, logger.lock)
    end
    parent = logger.logger
    if level ≥ Logging.min_enabled_level(parent) && Logging.shouldlog(parent, level, _module, group, id)
        Logging.handle_message(parent, level, message, _module, group, id, file, line; kwargs...)
    end
    return nothing
end

"""
    output_log_line(level, message; kwargs...)

Line of a warning or error in `hamster.out`: `Warning: ` or `Error: ` with the message and the values logged with it
(`key = value`); further lines of the message are indented.
"""
function output_log_line(level, message; kwargs...)
    text = string(message)
    for (key, value) in kwargs
        key == :maxlog && continue
        text *= "\n$key = $value"
    end
    prefix = level ≥ Logging.Error ? "Error: " : "Warning: "
    return prefix * replace(rstrip(text), "\n" => "\n  ")
end

"""
    log_to_output!(logger::OutputLogger, line; count=true)

Write `line` to the output file of `logger` (or keep it until [`start_output_log!`](@ref Hamster.start_output_log!)),
unless it was already written. `count` counts it as a warning for [`finish_output_log`](@ref Hamster.finish_output_log).
"""
function log_to_output!(logger::OutputLogger, line; count=true)
    lock(logger.lock) do
        line ∈ logger.written && return nothing
        push!(logger.written, line)
        count && (logger.nwarnings += 1)
        logger.started ? append_output_line(line, filename=logger.filename) : push!(logger.pending, line)
    end
    return nothing
end

"""
    start_output_log!(logger=Logging.current_logger())

Write the warnings and errors that `logger` (an [`OutputLogger`](@ref Hamster.OutputLogger)) has kept to its output
file and write later ones directly. Called after the header of `hamster.out` is written, or when the run fails before.
Does nothing for other loggers.
"""
start_output_log!(logger=Logging.current_logger()) = nothing

function start_output_log!(logger::OutputLogger)
    lock(logger.lock) do
        logger.started = true
        isempty(logger.pending) && return nothing
        open(logger.filename, "a") do io
            foreach(line -> println(io, line), logger.pending)
        end
        empty!(logger.pending)
    end
    return nothing
end

"""
    finish_output_log(logger=Logging.current_logger())

Append the number of warnings of the run to the output file of `logger` (an [`OutputLogger`](@ref Hamster.OutputLogger)),
if there were any. Does nothing for other loggers.
"""
finish_output_log(logger=Logging.current_logger()) = nothing

function finish_output_log(logger::OutputLogger)
    logger.nwarnings == 0 && return nothing
    s = logger.nwarnings == 1 ? "" : "s"
    append_output_line("\nThe run gave $(logger.nwarnings) warning$s, see the lines starting with \"Warning:\" above.",
                       filename=logger.filename)
    return nothing
end

"""
    output_logger(rank)

The logger of a run: on rank 0 an [`OutputLogger`](@ref Hamster.OutputLogger) around the current logger (the current
logger itself if it is one already, e.g., installed by the `hamster` command to keep the warnings of the config file),
otherwise the current logger.
"""
function output_logger(rank)
    logger = Logging.current_logger()
    rank == 0 || return logger
    logger isa OutputLogger || return OutputLogger(logger)
    logger.started = false
    logger.nwarnings = length(logger.pending)
    empty!(logger.written)
    union!(logger.written, logger.pending)
    return logger
end
